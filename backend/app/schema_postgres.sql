CREATE TABLE IF NOT EXISTS retreat_inventory_levels (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INTEGER REFERENCES retreat_inventory_items(id) ON DELETE CASCADE,
    category_id INTEGER REFERENCES retreat_inventory_categories(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 0,
    min_threshold INTEGER NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (item_id IS NOT NULL AND category_id IS NULL)
        OR
        (item_id IS NULL AND category_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_retreat_inventory_levels_item_unique
ON retreat_inventory_levels(item_id) WHERE item_id IS NOT NULL AND category_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_retreat_inventory_levels_category_unique
ON retreat_inventory_levels(category_id) WHERE category_id IS NOT NULL AND item_id IS NULL;


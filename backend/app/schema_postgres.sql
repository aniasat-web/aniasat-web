    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS recipe_steps (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
